#!/usr/bin/env node
// Regenerates src/config/tbcContent.js's RAID_LOOT table from AtlasLootClassic.
//
// The table answers "which raid, and which boss, does item 30095 come from" —
// Gargul exports carry nothing but the item id, and the boss an RCLootcouncil
// row names is the encounter that was current when the item was *awarded*, not
// where it dropped. So the item id has to be the primary key.
//
// The source is AtlasLootClassic's `data-tbc.lua`: one Lua table per instance,
// every boss carrying its full drop list by item id. It was picked over
// scraping Wowhead's zone pages (what this script used to do) for three
// reasons:
//   * it is complete — Wowhead's zone page attributes an NPC to barely a third
//     of the drops, which is how 198 items ended up with no boss at all and
//     Teron Gorefiend's twelve drops were missing from the table entirely,
//   * it names the *encounter* ("Reliquary of the Lost", "The Illidari
//     Council", "Eredar Twins") where Wowhead names whichever NPC technically
//     holds the loot ("Essence of Anger", "High Nethermancer Zerevor", "Grand
//     Warlock Alythess") — the encounter is what a raider calls the kill,
//   * it is one request against raw.githubusercontent.com instead of nine
//     against Wowhead, which rate-limits scrapers hard.
// Spot-checked against Wowhead's per-item "dropped by" lists: 224 of 224 items
// agreed.
//
// Run it when AtlasLoot ships corrections or a new tier opens (add the raid to
// RAIDS below):  node scripts/fetch-tbc-loot.js
// It rewrites src/config/tbcContent.js's generated block in place; the
// hand-written parts of that file (content metadata, lookup helpers) are kept.

const https = require("https");
const fs = require("fs");
const path = require("path");

const TARGET = path.join(__dirname, "..", "src", "config", "tbcContent.js");
const BEGIN = "// >>> generated by scripts/fetch-tbc-loot.js — do not edit by hand";
const END = "// <<< end generated";
const SOURCE = "https://raw.githubusercontent.com/Hoizame/AtlasLootClassic/master/AtlasLootClassic_DungeonsAndRaids/data-tbc.lua";

// content id → the `MapID` AtlasLoot files that instance under, which is the
// same id Wowhead uses for the zone. Order matches CONTENTS in tbcContent.js.
const RAIDS = [
    { content: "kara", map: 3457 },
    { content: "gruul", map: 3923 },
    { content: "mag", map: 3836 },
    { content: "ssc", map: 3607 },
    { content: "tk", map: 3845 },
    { content: "za", map: 3805 },
    { content: "hyjal", map: 3606 },
    { content: "bt", map: 3959 },
    { content: "swp", map: 4075 },
];

// A few AtlasLoot drop lists are filed under a heading that is not what the
// raid calls the encounter. Left of the colon is what the addon writes, right
// of it what the loot overview should show.
const RENAME = {
    // The Phase-4 legendary weapons are a tab of their own in AtlasLoot; in the
    // raid they drop from Kael'thas.
    "Legendaries": "Kael'thas Sunstrider",
    // Recipes and patterns off the instance's trash, listed separately.
    "Patterns": "Trash",
};

// Drop lists that are not TBC raid loot at all: "Prince Tenris Mirkblood" is
// the WotLK-era Karazhan Crypt event, which AtlasLoot files under Karazhan.
const SKIP_BOSSES = new Set(["Prince Tenris Mirkblood"]);

// Encounters that share one loot pool: an item dropping from every one of them
// is not ambiguous, it belongs to the group. The Opera Event rolls one of three
// plays, and its shared drops are the ones every play has.
const GROUPS = [
    { name: "Opera Event", members: ["The Wizard of Oz", "The Big Bad Wolf", "Romulo and Julianne"] },
];

// Raid drops AtlasLoot does not list, taken from Wowhead's per-item "dropped
// by" instead (checked 2026-07-31). Kept by hand because chasing five item
// pages is not worth keeping a second scraper alive.
const MANUAL = [
    { id: 23620, content: "kara", boss: "Trash" },              // Recipe, off Karazhan trash
    { id: 23633, content: "kara", boss: "Trash" },              // Recipe, off the Phantom Guests
    { id: 32386, content: "mag", boss: "Magtheridon" },
    { id: 32895, content: "ssc", boss: "Lady Vashj" },          // Vashj's Vial Remnant
    { id: 32896, content: "tk", boss: "Kael'thas Sunstrider" }, // Kael's Vial Remnant
];

function get(url, depth = 0) {
    return new Promise((resolve, reject) => {
        const req = https.get(url, { headers: { "User-Agent": "EventHelper loot-table generator" } }, (res) => {
            if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location && depth < 5) {
                res.resume();
                return resolve(get(res.headers.location, depth + 1));
            }
            let body = "";
            res.setEncoding("utf8");
            res.on("data", (c) => { body += c; });
            res.on("end", () => resolve({ status: res.statusCode, body }));
        });
        req.setTimeout(45000, () => req.destroy(new Error("timeout")));
        req.on("error", reject);
    });
}

/**
 * Reads AtlasLoot's Lua into Map(mapId → Map(boss → Set(itemId))).
 *
 * The file is regular enough to read line by line rather than with a Lua
 * parser: an instance opens with `data["Karazhan"] = {` and declares its
 * `MapID`, every boss inside `items = {` opens with `name = AL["…"]`, and each
 * drop is a `{ slot, itemId },` pair. Rows the addon hides are commented out
 * (`--{ 11, 29434 },`) and fail the same regex, which is what we want.
 */
function parse(lua) {
    const out = new Map();
    let mapId = 0, inItems = false, boss = "";
    for (const line of lua.split(/\r?\n/)) {
        if (/^data\[".+"\]\s*=\s*\{/.test(line)) { mapId = 0; inItems = false; boss = ""; continue; }
        const mMap = line.match(/^\s*MapID\s*=\s*(\d+)/);
        if (mMap) { mapId = Number(mMap[1]); continue; }
        if (/^\s*items\s*=\s*\{/.test(line)) { inItems = true; continue; }
        if (!inItems || !mapId) continue;
        const mName = line.match(/^\s*name\s*=\s*AL\["([^"]+)"\]/);
        if (mName) { boss = mName[1]; continue; }
        const mItem = line.match(/^\s*\{\s*\d+\s*,\s*(\d+)\s*(?:,[^}]*)?\}/);
        if (!mItem || !boss) continue;
        if (!out.has(mapId)) out.set(mapId, new Map());
        const byBoss = out.get(mapId);
        if (!byBoss.has(boss)) byBoss.set(boss, new Set());
        byBoss.get(boss).add(Number(mItem[1]));
    }
    return out;
}

/** The encounter name to file a drop list under, or "" to leave it out. */
function encounter(boss) {
    if (SKIP_BOSSES.has(boss)) return "";
    return RENAME[boss] || boss;
}

/** The group name when these encounters are one shared loot pool, else "". */
function groupOf(bosses) {
    if (bosses.length < 2) return "";
    const hit = GROUPS.find((g) => bosses.every((b) => g.members.includes(b)));
    return hit ? hit.name : "";
}

(async () => {
    const { status, body } = await get(SOURCE);
    if (status !== 200 || body.length < 10000) throw new Error(`source unreachable (status ${status})`);
    const parsed = parse(body);

    // item id → every (content, boss) it is listed under, so the ambiguous ones
    // can be recognised instead of being filed under whichever came first.
    const sources = new Map();
    for (const raid of RAIDS) {
        const byBoss = parsed.get(raid.map);
        if (!byBoss || !byBoss.size) throw new Error(`${raid.content}: nothing parsed for MapID ${raid.map}`);
        for (const [rawBoss, ids] of byBoss) {
            const boss = encounter(rawBoss);
            if (!boss) continue;
            for (const id of ids) {
                if (!sources.has(id)) sources.set(id, []);
                sources.get(id).push({ content: raid.content, boss });
            }
        }
    }
    for (const m of MANUAL) sources.set(m.id, [{ content: m.content, boss: m.boss }]);

    const table = {};
    for (const r of RAIDS) table[r.content] = new Map();
    let ambiguous = 0, unattributed = 0;
    for (const [id, found] of sources) {
        const contents = [...new Set(found.map((f) => f.content))];
        // A BoE off the trash of several raids cannot be placed by its id at
        // all. Leaving it out of the table is deliberate: the loot row then
        // falls back to the instance string its export named, which is the only
        // thing left that can tell the two apart.
        if (contents.length > 1) { ambiguous++; continue; }
        const bosses = [...new Set(found.map((f) => f.boss))];
        const boss = bosses.length === 1 ? bosses[0] : groupOf(bosses);
        if (!boss) unattributed++;
        const byBoss = table[contents[0]];
        if (!byBoss.has(boss)) byBoss.set(boss, []);
        byBoss.get(boss).push(id);
    }

    const blocks = RAIDS.map((r) => {
        const byBoss = table[r.content];
        const lines = [...byBoss.entries()]
            .sort((a, b) => (a[0] ? 0 : 1) - (b[0] ? 0 : 1) || a[0].localeCompare(b[0]))
            .map(([boss, ids]) => `        ${JSON.stringify(boss)}: [${[...new Set(ids)].sort((a, b) => a - b).join(", ")}],`);
        const count = [...byBoss.values()].reduce((s, ids) => s + ids.length, 0);
        console.log(`${r.content.padEnd(6)} ${String(count).padStart(4)} items, ${byBoss.size} source(s)`);
        return `    ${r.content}: {\n${lines.join("\n")}\n    },`;
    });
    console.log(`skipped ${ambiguous} item(s) dropping in more than one raid, ${unattributed} without a single encounter`);

    const generated = `${BEGIN}\nconst RAID_LOOT = {\n${blocks.join("\n")}\n};\n${END}`;
    const src = fs.readFileSync(TARGET, "utf8");
    const start = src.indexOf(BEGIN);
    const end = src.indexOf(END);
    if (start === -1 || end === -1) throw new Error(`markers not found in ${TARGET}`);
    fs.writeFileSync(TARGET, src.slice(0, start) + generated + src.slice(end + END.length));
    console.log(`wrote ${TARGET}`);
})().catch((e) => {
    console.error(e.message);
    process.exitCode = 1;
});
