#!/usr/bin/env node
// Regenerates src/config/tbcContent.js's RAID_LOOT table from Wowhead.
//
// Each TBC raid zone page ships its loot tab as an inline
// `Listview({ id: 'drops', … data:[…] })` array carrying every item id, name and
// (where Wowhead has the attribution) the boss that drops it. That is the only
// place we can get "which raid does item 30049 come from" — Gargul exports carry
// nothing but the item id, so without this table a Gargul-only guild could not
// filter its loot by content at all.
//
// Run it when a new tier opens (add the zone below) or when the table looks
// stale:  node scripts/fetch-tbc-loot.js
// It rewrites src/config/tbcContent.js's generated block in place; the
// hand-written parts of that file (content metadata, lookup helpers) are kept.

const https = require("https");
const fs = require("fs");
const path = require("path");

const TARGET = path.join(__dirname, "..", "src", "config", "tbcContent.js");
const BEGIN = "// >>> generated by scripts/fetch-tbc-loot.js — do not edit by hand";
const END = "// <<< end generated";

// content id → Wowhead zone id. Order matches CONTENTS in tbcContent.js.
const ZONES = [
    { content: "kara", zone: 3457 },
    { content: "gruul", zone: 3923 },
    { content: "mag", zone: 3836 },
    { content: "ssc", zone: 3607 },
    { content: "tk", zone: 3845 },
    { content: "za", zone: 3805 },
    { content: "hyjal", zone: 3606 },
    { content: "bt", zone: 3959 },
    { content: "swp", zone: 4075 },
];

function get(url, depth = 0) {
    return new Promise((resolve, reject) => {
        https.get(url, { headers: { "User-Agent": "Mozilla/5.0 (EventHelper)" } }, (res) => {
            if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location && depth < 5) {
                res.resume();
                const next = res.headers.location.startsWith("http")
                    ? res.headers.location
                    : `https://www.wowhead.com${res.headers.location}`;
                return resolve(get(next, depth + 1));
            }
            let body = "";
            res.setEncoding("utf8");
            res.on("data", (c) => { body += c; });
            res.on("end", () => resolve({ status: res.statusCode, body }));
        }).on("error", reject);
    });
}

// Pull the JSON array out of `… id: 'drops', … data:[ … ]`. Brace counting
// rather than a regex: the array contains item names with brackets in them.
function extractDrops(html) {
    const i = html.indexOf("id: 'drops'");
    if (i === -1) return null;
    const arrStart = html.indexOf("[", html.indexOf("data:", i));
    let depth = 0;
    for (let j = arrStart; j < html.length; j++) {
        const ch = html[j];
        if (ch === "[") depth++;
        else if (ch === "]") {
            depth--;
            if (depth === 0) return JSON.parse(html.slice(arrStart, j + 1));
        } else if (ch === "\"") {
            j++;
            while (j < html.length && html[j] !== "\"") { if (html[j] === "\\") j++; j++; }
        }
    }
    return null;
}

// `sourcemore` entries with t === 1 are NPCs (the boss). Some items have no NPC
// attribution on Wowhead at all (trash, or a gap in their data) — those land
// under "" and still get their content, which is what the filters need.
function bossOf(row) {
    const npc = (row.sourcemore || []).find((s) => s && s.t === 1 && s.n);
    return npc ? String(npc.n) : "";
}

(async () => {
    const blocks = [];
    for (const z of ZONES) {
        const { body } = await get(`https://www.wowhead.com/tbc/zone=${z.zone}`);
        const drops = extractDrops(body);
        if (!drops || !drops.length) {
            console.error(`! ${z.content} (zone=${z.zone}): no drop table found — keeping the old entry`);
            process.exitCode = 1;
            return;
        }
        const byBoss = new Map();
        for (const row of drops) {
            const id = Number(row.id) || 0;
            if (!id) continue;
            const boss = bossOf(row);
            if (!byBoss.has(boss)) byBoss.set(boss, []);
            byBoss.get(boss).push(id);
        }
        const bosses = [...byBoss.entries()]
            .sort((a, b) => (a[0] ? 0 : 1) - (b[0] ? 0 : 1) || a[0].localeCompare(b[0]))
            .map(([boss, ids]) => `        ${JSON.stringify(boss)}: [${[...new Set(ids)].sort((a, b) => a - b).join(", ")}],`);
        blocks.push(`    ${z.content}: {\n${bosses.join("\n")}\n    },`);
        console.log(`${z.content}: ${drops.length} items, ${byBoss.size} source(s)`);
    }

    const generated = `${BEGIN}\nconst RAID_LOOT = {\n${blocks.join("\n")}\n};\n${END}`;
    const src = fs.readFileSync(TARGET, "utf8");
    const start = src.indexOf(BEGIN);
    const end = src.indexOf(END);
    if (start === -1 || end === -1) throw new Error(`markers not found in ${TARGET}`);
    fs.writeFileSync(TARGET, src.slice(0, start) + generated + src.slice(end + END.length));
    console.log(`wrote ${TARGET}`);
})().catch((e) => {
    console.error(e.message);
    process.exitCode = 1;
});
